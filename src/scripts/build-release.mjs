// Release build for static hosts (GitHub Pages): a transport-only esbuild
// step that repackages the unmodified native-ESM source into split, minified
// chunks. Nothing about the authored code changes — dev mode still serves
// raw index.html + import map; only the deploy artifact is bundled.
//
// The entry set mirrors every module the browser reaches through a
// runtime-constructed dynamic import (not greppable as a literal, so each is
// an explicit entry point):
//   - src/host/browser-host.js  — the boot entry (script tag in index.html)
//   - each plugin entry from bootstrap.json (loaded by browser-host.js:55)
//   - src/ui/index.js           — the UI entry (same mechanism)
//   - config/config.js          — the user config module (user-config.js:119)
//   - src/ui/pages/docs/docs.js — pinned to its source depth so its relative
//     new URL(..., import.meta.url) constants keep resolving after the move
// Everything reachable only through literal dynamic imports (the not-found
// page, the router adapters) becomes its own lazy chunk automatically.
//
// Run with: node src/scripts/build-release.mjs [--outdir dist]

import { build } from 'esbuild';
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

const ENTRY_POINTS = [
  'src/host/browser-host.js',
  'src/plugins/pey.storage/index.js',
  'src/plugins/pey.router/index.js',
  'src/plugins/shirazeh.http/index.js',
  'src/plugins/pey.markdown/index.js',
  'src/plugins/shirazeh.docs/index.js',
  'src/plugins/shirazeh.prefs/index.js',
  'src/ui/index.js',
  'src/ui/pages/docs/docs.js',
  'config/config.js',
].map((entry) => join(PROJECT_ROOT, entry));

// Same per-specifier mapping as the dev import map in index.html: the
// "pey.webui/<path>" specifiers resolve to ui-kit files (some to a file other
// than <path>.js), so a plain directory alias is not enough.
const WEBUI_ALIAS = Object.freeze({
  'pey.webui/contracts': 'src/ui-kit/contracts.js',
  'pey.webui/shared-state': 'src/ui-kit/shared-state.js',
  'pey.webui/base/pey-element': 'src/ui-kit/base/pey-element.js',
  'pey.webui/base/icon-sprite': 'src/ui-kit/base/icon-sprite.js',
  'pey.webui/base/attach-style-sheet': 'src/ui-kit/base/attach-style-sheet.js',
  'pey.webui/shell/create-application-setup': 'src/ui-kit/shell/create-application-setup.js',
  'pey.webui/shell/app-shell': 'src/ui-kit/shell/app-shell.js',
  'pey.webui/routing/page-loader': 'src/ui-kit/routing/page-loader.js',
  'pey.webui/routing/page-host': 'src/ui-kit/routing/page-host.js',
  'pey.webui/routing/page-fallback': 'src/ui-kit/routing/page-fallback.js',
  'pey.webui/i18n': 'src/ui-kit/i18n/create-i18n.js',
  'pey.webui/i18n/catalog': 'src/ui-kit/i18n/catalog.js',
});
// Alias values resolve relative to the process cwd — pin them to the project.
const alias = Object.fromEntries(
  Object.entries(WEBUI_ALIAS).map(([specifier, path]) => [specifier, join(PROJECT_ROOT, path)]),
);

// Static (unbundled) files the running site fetches at runtime: stylesheets,
// fonts and icons referenced by URL, the docs pages, the plugin/UI manifests
// fetched by the core, and the vendored highlight.js assets loaded by
// src/ui/pages/docs/highlight.js. The built index.html points at the same
// paths, so the layout must match the repository exactly.
const STATIC_DIRS = ['docs', 'src/ui/assets', 'src/ui/styles', 'src/vendor/highlight'];
const STATIC_FILES = ['bootstrap.json', 'src/ui-kit/tokens.css', 'src/ui/manifest.json'];
const STATIC_MANIFESTS = [
  'src/plugins/pey.storage/manifest.json',
  'src/plugins/pey.router/manifest.json',
  'src/plugins/shirazeh.http/manifest.json',
  'src/plugins/pey.markdown/manifest.json',
  'src/plugins/shirazeh.docs/manifest.json',
  'src/plugins/shirazeh.prefs/manifest.json',
];

const IMPORT_MAP_MARKER = /<script type="importmap">[\s\S]*?<\/script>\n?/;
const PRELOAD_MARKER = /^[ \t]*<!-- Module preloads \(generated by npm run build:import-map — do not edit\) -->\n[\s\S]*?^[ \t]*<!-- \/Module preloads -->\n?/m;
const RELATIVE_URL_PATTERN = /new URL\(\s*['"](\.[^'"]*)['"]|import\(\s*['"](\.[^'"]*)['"]/g;

function parseOutdir(argv) {
  const index = argv.indexOf('--outdir');
  const value = index >= 0 ? argv[index + 1] : null;
  if (!value || value.startsWith('-')) {
    return join(PROJECT_ROOT, 'dist');
  }
  return resolve(PROJECT_ROOT, value);
}

/** Normalizes an esbuild metafile output key to an absolute path. */
function toAbsolute(outputPath) {
  return isAbsolute(outputPath) ? outputPath : resolve(process.cwd(), outputPath);
}

/** The deploy HTML: dev index.html minus the import map, plus chunk preloads. */
function buildReleaseHtml(devHtml, preloadPaths) {
  const preloads = preloadPaths
    .map((path) => `  <link rel="modulepreload" href="${path}">`)
    .join('\n');
  const block = `  <!-- Chunk preloads (generated by npm run build:release — do not edit) -->\n${preloads}\n  <!-- /Chunk preloads -->\n`;

  let html = devHtml.replace(IMPORT_MAP_MARKER, '');
  if (html === devHtml) {
    throw new Error('release build: no import-map block found in index.html');
  }
  if (!PRELOAD_MARKER.test(html)) {
    throw new Error('release build: no module-preload marker block found in index.html');
  }
  html = html.replace(PRELOAD_MARKER, block);
  return html;
}

/**
 * Transport-correctness guard: every relative URL or dynamic import left in
 * a chunk must resolve to a real file inside the outdir — a moved chunk that
 * broke its new URL(..., import.meta.url) depth would otherwise 404 at
 * runtime, in the browser only.
 */
async function guardRelativeReferences(outdir) {
  const failures = [];
  const jsFiles = [];
  const walk = async (dir) => {
    for (const name of await readdir(dir)) {
      const full = join(dir, name);
      if ((await stat(full)).isDirectory()) {
        await walk(full);
      } else if (name.endsWith('.js')) {
        jsFiles.push(full);
      }
    }
  };
  await walk(outdir);

  for (const file of jsFiles) {
    const source = await readFile(file, 'utf8');
    for (const match of source.matchAll(RELATIVE_URL_PATTERN)) {
      const specifier = match[1] ?? match[2];
      const target = resolve(dirname(file), specifier);
      if (!target.startsWith(outdir) || !(await stat(target).catch(() => null))) {
        failures.push(`${relative(outdir, file)} -> ${specifier}`);
      }
    }
  }
  if (failures.length > 0) {
    throw new Error(`release build: broken relative references in the output:\n  ${failures.join('\n  ')}`);
  }
}

const outdir = parseOutdir(process.argv);
await rm(outdir, { recursive: true, force: true });
await mkdir(outdir, { recursive: true });

const result = await build({
  entryPoints: ENTRY_POINTS,
  outbase: PROJECT_ROOT,
  outdir,
  bundle: true,
  splitting: true,
  format: 'esm',
  minify: true,
  sourcemap: false,
  platform: 'browser',
  charset: 'utf8',
  legalComments: 'none',
  nodePaths: [join(PROJECT_ROOT, 'src/vendor/node_modules')],
  alias,
  loader: { '.css': 'file' },
  metafile: true,
  logLevel: 'warning',
});

// Static chunk classification: the declared entries and every shared chunk
// are preloaded; chunks esbuild created for literal dynamic imports (the
// not-found page, the router adapters) carry an entryPoint that is not in
// the declared set and stay on demand.
const bootOutput = join(outdir, 'src/host/browser-host.js');
const declaredEntries = new Set(ENTRY_POINTS);
const entryChunks = new Set([bootOutput]);
const lazyChunks = new Set();
for (const [key, output] of Object.entries(result.metafile.outputs)) {
  if (!key.endsWith('.js')) {
    continue;
  }
  const outputAbs = toAbsolute(key);
  if (typeof output.entryPoint === 'string') {
    if (declaredEntries.has(resolve(output.entryPoint))) {
      entryChunks.add(outputAbs);
    } else {
      lazyChunks.add(outputAbs);
    }
  }
}
const preloadPaths = Object.keys(result.metafile.outputs)
  .filter((key) => key.endsWith('.js'))
  .map(toAbsolute)
  .filter((outputAbs) => !entryChunks.has(outputAbs) && !lazyChunks.has(outputAbs))
  .concat([...entryChunks].filter((outputAbs) => outputAbs !== bootOutput))
  .map((outputAbs) => relative(outdir, outputAbs))
  .sort();

for (const dir of STATIC_DIRS) {
  await cp(join(PROJECT_ROOT, dir), join(outdir, dir), { recursive: true });
}
for (const file of [...STATIC_FILES, ...STATIC_MANIFESTS]) {
  await mkdir(dirname(join(outdir, file)), { recursive: true });
  await cp(join(PROJECT_ROOT, file), join(outdir, file));
}
// Only the markdown config files are fetched at runtime; config.js itself is
// an entry chunk emitted by esbuild above and must not be overwritten.
for (const name of await readdir(join(PROJECT_ROOT, 'config'))) {
  if (name.endsWith('.md')) {
    await cp(join(PROJECT_ROOT, 'config', name), join(outdir, 'config', name));
  }
}

const devHtml = await readFile(join(PROJECT_ROOT, 'index.html'), 'utf8');
await writeFile(join(outdir, 'index.html'), buildReleaseHtml(devHtml, preloadPaths), 'utf8');

await guardRelativeReferences(outdir);

const jsChunks = Object.keys(result.metafile.outputs).filter((path) => path.endsWith('.js'));
const jsBytes = jsChunks.reduce((sum, path) => {
  const size = result.metafile.outputs[path].bytes;
  return sum + (typeof size === 'number' ? size : 0);
}, 0);
console.log(`release build: ${jsChunks.length} JS chunks, ${(jsBytes / 1024).toFixed(0)} KiB minified`);
console.log(`release build: ${preloadPaths.length} preloaded chunks (${entryChunks.size} entry chunks)`);
console.log(`release build: output in ${relative(PROJECT_ROOT, outdir)}`);
