// Regression test for the release build (src/scripts/build-release.mjs):
// the transport-only esbuild bundle must produce every chunk the browser
// reaches through runtime-constructed dynamic imports, keep all runtime
// fetch targets on disk, ship an index.html without the dev import map, and
// leave the lazy chunks (not-found page, router adapters) out of the preload
// list. The script itself already guards broken relative references; this
// test pins the observable shape of the artifact.

import assert from 'node:assert/strict';
import test from 'node:test';
import { execFile } from 'node:child_process';
import { mkdtemp, readFile, readdir, rm, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const run = promisify(execFile);
const SCRIPT = fileURLToPath(new URL('../scripts/build-release.mjs', import.meta.url));

const ENTRY_CHUNKS = [
  'src/host/browser-host.js',
  'src/plugins/pey.storage/index.js',
  'src/plugins/pey.router/index.js',
  'src/plugins/shirazeh.http/index.js',
  'src/plugins/pey.markdown/index.js',
  'src/plugins/shirazeh.docs/index.js',
  'src/plugins/shirazeh.prefs/index.js',
  'src/ui/index.js',
  'src/ui/pages/docs/docs.js',
  'config/config.js',
];

const RUNTIME_FETCH_TARGETS = [
  'bootstrap.json',
  'config/sidebar.md',
  'config/navbar.md',
  'config/404.md',
  'docs/README.md',
  'src/ui/manifest.json',
  'src/ui-kit/tokens.css',
  'src/ui/styles/app.css',
  'src/ui/styles/fonts.css',
  'src/ui/styles/content.css',
  'src/ui/assets/shirazeh.svg',
  'src/ui/assets/icons.svg',
  'src/ui/assets/fonts/Vazirmatn-Regular.woff2',
  'src/vendor/highlight/highlight.min.js',
  'src/vendor/highlight/github-light.min.css',
  'src/vendor/highlight/github-dark.min.css',
  'src/plugins/pey.storage/manifest.json',
  'src/plugins/pey.router/manifest.json',
  'src/plugins/shirazeh.http/manifest.json',
  'src/plugins/pey.markdown/manifest.json',
  'src/plugins/shirazeh.docs/manifest.json',
  'src/plugins/shirazeh.prefs/manifest.json',
];

let dist = null;

test.before(async () => {
  dist = await mkdtemp(join(tmpdir(), 'shirazeh-release-'));
  await run('node', [SCRIPT, '--outdir', dist]);
});

test.after(async () => {
  await rm(dist, { recursive: true, force: true });
});

async function listJsChunks() {
  const files = [];
  const walk = async (dir) => {
    for (const name of await readdir(dir, { withFileTypes: true })) {
      const full = join(dir, name.name);
      if (name.isDirectory()) {
        await walk(full);
      } else if (name.name.endsWith('.js')) {
        files.push(full);
      }
    }
  };
  await walk(dist);
  return files;
}

test('should_emit_every_entry_chunk_the_boot_mechanism_imports', async () => {
  for (const entry of ENTRY_CHUNKS) {
    await assert.doesNotReject(() => stat(join(dist, entry)), `missing entry chunk: ${entry}`);
  }
});

test('should_ship_every_runtime_fetch_target', async () => {
  for (const target of RUNTIME_FETCH_TARGETS) {
    await assert.doesNotReject(() => stat(join(dist, target)), `missing runtime file: ${target}`);
  }
});

test('should_release_index_html_without_the_dev_import_map_and_with_preloads', async () => {
  const html = await readFile(join(dist, 'index.html'), 'utf8');
  assert.doesNotMatch(html, /<script type="importmap">/);
  assert.match(html, /Chunk preloads \(generated by npm run build:release/);
  assert.match(html, /<script type="module" src="src\/host\/browser-host.js"><\/script>/);
  const preloadBlock = html.match(/<!-- Chunk preloads[\s\S]*?<!-- \/Chunk preloads -->/);
  assert.ok(preloadBlock, 'preload block missing');
  for (const entry of ENTRY_CHUNKS.slice(1)) {
    assert.match(preloadBlock[0], new RegExp(`href="${entry.replaceAll('.', '\\.')}"`), `not preloaded: ${entry}`);
  }
});

test('should_keep_lazy_chunks_out_of_the_preload_block', async () => {
  const html = await readFile(join(dist, 'index.html'), 'utf8');
  const preloadBlock = html.match(/<!-- Chunk preloads[\s\S]*?<!-- \/Chunk preloads -->/)[0];
  for (const file of await listJsChunks()) {
    const name = file.slice(dist.length + 1);
    if (!ENTRY_CHUNKS.includes(name) && name !== 'src/host/browser-host.js' && !/chunk-/.test(name)) {
      // Every non-entry, non-shared chunk is a lazy dynamic-import target and
      // must stay on demand.
      assert.doesNotMatch(preloadBlock, new RegExp(`href="${name.replaceAll('.', '\\.')}"`), `lazy chunk preloaded: ${name}`);
    }
  }
});

test('should_bundle_the_vendor_tree_without_node_modules_references', async () => {
  for (const file of await listJsChunks()) {
    const source = await readFile(file, 'utf8');
    assert.doesNotMatch(source, /src\/vendor\/node_modules/, `unresolved vendor reference in ${file}`);
    assert.doesNotMatch(source, /node_modules/, `node_modules reference in ${file}`);
  }
});

test('should_keep_the_plugin_entry_contract_intact', async () => {
  for (const entry of ENTRY_CHUNKS.slice(1, 7)) {
    const source = await readFile(join(dist, entry), 'utf8');
    assert.match(source, /as prepare\b/, `plugin entry lost its prepare export: ${entry}`);
    assert.match(source, /as activate\b/, `plugin entry lost its activate export: ${entry}`);
  }
});
